/**
 * Live plans of the Kiorly page (browser side). The page holds NO plan, price or feature of its own: it reads the platform's public, read-only contract
 * `kiorly.public-plans.v1` (GET <platform>/api/v1/public/plans) when the page loads. Anything unexpected in the answer, or any failure to fetch it, leaves the static
 * 'plans are being finalised' text in place: a price is shown only when the contract carries one. Rendering escapes every value; nothing is stored in the browser.
 */
export type Lang = 'ar' | 'en';
export interface PlanPrice { interval: 'MONTHLY' | 'ANNUAL'; unit: 'PER_TENANT' | 'PER_CLINICIAN'; amount: string; currency: string; includedClinicians: number; extraClinicianAmount: string | null }
export interface PlanView { id: string; name: string; summary: string | null; limits: string[]; features: string[]; prices: PlanPrice[] }
export interface ModuleView { id: 'clinic' | 'pharmacy' | 'lab'; unavailable: boolean; plans: PlanView[] }
export interface PlansModel { market: { code: string; currency: string } | null; modules: ModuleView[] }
/** The words of the section in one language, generated by the build (the client bundle carries no copy of its own). */
export interface PlansLabels {
  tabs: string; modules: Record<'clinic' | 'pharmacy' | 'lab', string>; tbd: string; ask: string; includes: string; free: string; unavailable: string; marketNote: string;
  perMonth: string; perYear: string; perClinic: string; perClinician: string; included: string; extra: string; noPlans: string; more: string;
}

const MODULE_IDS = ['clinic', 'pharmacy', 'lab'] as const;
const isObj = (v: unknown): v is Record<string, unknown> => !!v && typeof v === 'object' && !Array.isArray(v);
const text = (v: unknown, max = 240): string | null => (typeof v === 'string' && v.trim() && v.length <= max ? v.trim() : null);
const MONEY = /^\d{1,12}(\.\d{1,2})?$/;

/** Strict reader of the contract: returns null for anything that is not exactly what v1 promises (the page then keeps its fallback text). */
export function parsePlans(raw: unknown, lang: Lang): PlansModel | null {
  if (!isObj(raw) || raw.contract !== 'kiorly.public-plans.v1' || !Array.isArray(raw.modules)) return null;
  const loc = (v: unknown): string | null => (isObj(v) ? text(v[lang]) : null);
  const lines = (v: unknown): string[] | null => {
    if (!isObj(v) || !Array.isArray(v[lang])) return null;
    const out = (v[lang] as unknown[]).map((x) => text(x)); return out.length <= 30 && out.every((x): x is string => x !== null) ? out : null;
  };
  const modules: ModuleView[] = [];
  for (const m of raw.modules as unknown[]) {
    if (!isObj(m) || !(MODULE_IDS as readonly string[]).includes(m.id as string) || !Array.isArray(m.plans)) return null;
    const plans: PlanView[] = [];
    for (const p of m.plans as unknown[]) {
      if (!isObj(p)) return null;
      const id = text(p.id, 40); const name = loc(p.name); const limits = lines(p.limits); const features = lines(p.features);
      if (!id || !/^[a-z0-9_-]+$/.test(id) || !name || !limits || !features || !Array.isArray(p.prices)) return null;
      const prices: PlanPrice[] = [];
      for (const x of p.prices as unknown[]) {
        if (!isObj(x) || !MONEY.test(String(x.amount)) || !/^[A-Z]{3}$/.test(String(x.currency)) || !['MONTHLY', 'ANNUAL'].includes(String(x.interval)) || !['PER_TENANT', 'PER_CLINICIAN'].includes(String(x.unit))) return null;
        const extra = x.extraClinicianAmount == null ? null : MONEY.test(String(x.extraClinicianAmount)) ? String(x.extraClinicianAmount) : undefined;
        if (extra === undefined) return null;
        prices.push({ interval: x.interval as PlanPrice['interval'], unit: x.unit as PlanPrice['unit'], amount: String(x.amount), currency: String(x.currency), includedClinicians: typeof x.includedClinicians === 'number' ? x.includedClinicians : 1, extraClinicianAmount: extra });
      }
      plans.push({ id, name, summary: p.summary == null ? null : loc(p.summary), limits, features, prices });
    }
    modules.push({ id: m.id as ModuleView['id'], unavailable: m.status === 'UNAVAILABLE', plans });
  }
  const mk = isObj(raw.market) && /^[A-Z]{2}$/.test(String(raw.market.code)) && /^[A-Z]{3}$/.test(String(raw.market.currency)) ? { code: String(raw.market.code), currency: String(raw.market.currency) } : null;
  return { market: mk, modules };
}

export const esc = (s: string): string => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');

/** An amount in its own currency: whole numbers without decimals, otherwise two. Arabic uses the Egyptian locale digits. */
export function formatMoney(amount: string, currency: string, lang: Lang): string {
  const n = Number(amount); const frac = amount.includes('.') && !/\.0+$/.test(amount) ? 2 : 0;
  try { return new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en', { style: 'currency', currency, minimumFractionDigits: frac, maximumFractionDigits: frac }).format(n); } catch { return `${amount} ${currency}`; }
}

const MODULE_JOIN: Record<ModuleView['id'], { module: string; type: string }> = { clinic: { module: 'CLINIC', type: 'CLINIC' }, pharmacy: { module: 'PHARMACY', type: 'PHARMACY' }, lab: { module: 'LAB', type: 'LAB' } };

function priceBlock(p: PlanView, lang: Lang, L: PlansLabels): string {
  if (!p.prices.length) return `<p class="plan-price tbd" data-price-status="tbd">${esc(L.tbd)}</p>`;
  const rows = p.prices.map((x) => {
    const money = x.amount === '0' || Number(x.amount) === 0 ? esc(L.free) : `<bdi>${esc(formatMoney(x.amount, x.currency, lang))}</bdi>`;
    const per = `${x.unit === 'PER_CLINICIAN' ? L.perClinician : L.perClinic} / ${x.interval === 'MONTHLY' ? L.perMonth : L.perYear}`;
    const extra = x.extraClinicianAmount ? `<small>${esc(L.extra)}: <bdi>${esc(formatMoney(x.extraClinicianAmount, x.currency, lang))}</bdi></small>` : '';
    return `<li data-interval="${x.interval}"><span class="amt">${money}</span> <span class="per">${esc(per)}</span>${extra}</li>`;
  }).join('');
  return `<ul class="plan-price" data-price-status="set">${rows}</ul>`;
}

const SHOWN_FEATURES = 6;
const tick = (x: string) => `<li><svg class="ic" aria-hidden="true" focusable="false"><use href="#i-check"/></svg><span>${esc(x)}</span></li>`;
/** The first few features are always visible; a long list folds the rest into a native disclosure (no script, keyboard and screen reader friendly). */
function featureList(f: string[], L: PlansLabels): string {
  if (!f.length) return '';
  const head = f.slice(0, SHOWN_FEATURES); const rest = f.slice(SHOWN_FEATURES);
  return `<p class="muted">${esc(L.includes)}</p><ul class="ticks">${head.map(tick).join('')}</ul>${rest.length ? `<details class="more"><summary>${esc(L.more.replace('{n}', String(rest.length)))}</summary><ul class="ticks">${rest.map(tick).join('')}</ul></details>` : ''}`;
}

export function renderPlan(mod: ModuleView['id'], p: PlanView, lang: Lang, L: PlansLabels): string {
  const j = MODULE_JOIN[mod];
  return `<li class="plan" data-plan="${esc(mod)}-${esc(p.id)}"><h3>${esc(p.name)}</h3>${p.summary ? `<p class="plan-sum">${esc(p.summary)}</p>` : ''}${priceBlock(p, lang, L)}`
    + `${p.limits.length ? `<ul class="plan-limits">${p.limits.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>` : ''}`
    + featureList(p.features, L)
    + `<p><a class="btn ghost" href="#join" data-join-mode="" data-join-module="${j.module}" data-join-type="${j.type}">${esc(L.ask)}</a></p></li>`;
}

/** Tabs for the products that have something to show; null when there is nothing to show at all (the fallback text stays). */
export function renderPlans(m: PlansModel, lang: Lang, L: PlansLabels): string | null {
  const shown = m.modules.filter((x) => x.plans.length > 0 || x.unavailable);
  if (!shown.some((x) => x.plans.length)) return null; // every product empty or down: the static text says it better
  const tabs = shown.map((x, i) => `<button type="button" role="tab" id="ptab-${x.id}" aria-controls="ppanel-${x.id}" aria-selected="${i === 0}" tabindex="${i === 0 ? 0 : -1}" class="ftab">${esc(L.modules[x.id])}</button>`).join('');
  const panels = shown.map((x, i) => `<div role="tabpanel" id="ppanel-${x.id}" aria-labelledby="ptab-${x.id}" tabindex="0"${i === 0 ? '' : ' hidden'}>${x.plans.length ? `<ul class="plans">${x.plans.map((p) => renderPlan(x.id, p, lang, L)).join('')}</ul>` : `<div class="note-box"><p>${esc(x.unavailable ? L.unavailable : L.noPlans)}</p></div>`}</div>`).join('');
  const hasPrice = shown.some((x) => x.plans.some((p) => p.prices.length));
  const note = m.market && hasPrice ? `<p class="muted plans-market" data-market="${esc(m.market.code)}">${esc(L.marketNote.replace('{currency}', m.market.currency).replace('{market}', m.market.code))}</p>` : '';
  return `<div class="ftabs" role="tablist" aria-label="${esc(L.tabs)}">${tabs}</div>${panels}${note}`;
}

/** Fetches the contract and, only if it is valid, replaces the static fallback inside `host`. Resolves to what happened (for tests and the status attribute). */
export async function mountPlans(host: HTMLElement, o: { endpoint: string; lang: Lang; labels: PlansLabels; bind: (tablist: HTMLElement) => void; fetchImpl?: typeof fetch; timeoutMs?: number }): Promise<'live' | 'fallback'> {
  const target = host.querySelector<HTMLElement>('[data-plans-live]'); const fallback = host.querySelector<HTMLElement>('[data-plans-fallback]');
  if (!target) return 'fallback';
  const ctl = new AbortController(); const timer = setTimeout(() => ctl.abort(), o.timeoutMs ?? 6000);
  try {
    const res = await (o.fetchImpl ?? fetch)(o.endpoint, { method: 'GET', headers: { accept: 'application/json' }, credentials: 'omit', referrerPolicy: 'no-referrer', signal: ctl.signal });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const model = parsePlans(await res.json(), o.lang);
    const html = model ? renderPlans(model, o.lang, o.labels) : null;
    if (!html) throw new Error('nothing to show');
    target.innerHTML = html; target.hidden = false; if (fallback) fallback.hidden = true;
    const list = target.querySelector<HTMLElement>('[role=tablist]'); if (list) o.bind(list);
    for (const el of target.querySelectorAll('.plan')) el.classList.add('is-in');
    host.dataset.state = 'live'; return 'live';
  } catch {
    host.dataset.state = 'fallback'; return 'fallback';
  } finally { clearTimeout(timer); }
}
